"""
Antigravity Verifiable Artifacts Manager: generates structured deliverables for Antigravity's Manager and Editor views.
"""

from pathlib import Path
from typing import Dict, Any, List
from forgeagent.state.state import TaskState
from forgeagent.agents.planner import DevelopmentPlan


class AntigravityArtifactManager:
    def __init__(self, workspace_root: str):
        self.workspace_root = Path(workspace_root)
        self.artifacts_dir = self.workspace_root / ".agents" / "artifacts"
        self.artifacts_dir.mkdir(parents=True, exist_ok=True)

    def write_implementation_plan(self, plan: DevelopmentPlan) -> Path:
        """Create Antigravity Implementation Plan Artifact."""
        path = self.artifacts_dir / "implementation_plan.md"
        tasks_md = "\n".join([
            f"### Task {t.id}: {t.title}\n"
            f"- **Description**: {t.description}\n"
            f"- **Target Files**: {', '.join(t.target_files) if t.target_files else 'None'}\n"
            f"- **Dependencies**: {', '.join(t.dependencies) if t.dependencies else 'None'}\n"
            f"- **Status**: `{t.status}`\n"
            for t in plan.tasks
        ])
        criteria_md = "\n".join([f"- [ ] {c}" for c in plan.acceptance_criteria])

        content = f"""# Implementation Plan: {plan.project}

> **Antigravity Verifiable Artifact**  
> Generated autonomously by **ForgeAgent**

## Project Overview
{plan.description or 'Autonomous software engineering task execution.'}

## Target Architecture & Technology Stack
- **Frontend**: {plan.stack.get('frontend', 'None')}
- **Backend**: {plan.stack.get('backend', 'None')}
- **Database**: {plan.stack.get('database', 'None')}
- **Test Runner**: {plan.stack.get('test_runner', 'Auto-detected')}

---

## Phased Work Breakdown
{tasks_md}

---

## Acceptance Criteria
{criteria_md}
"""
        path.write_text(content, encoding="utf-8")
        return path

    def write_walkthrough(self, state: TaskState, summary: str = "") -> Path:
        """Create Antigravity Walkthrough & Code Diff Artifact."""
        path = self.artifacts_dir / "walkthrough.md"
        files_md = "\n".join([f"- `{f}`" for f in state.changed_files])
        content = f"""# Walkthrough & Changes: {state.project_id}

> **Antigravity Verifiable Artifact**  
> Status: **{state.phase.value.upper()}** | Iteration: **{state.iteration}**

## Summary of Changes
{summary or 'All tasks implemented and verified through the autonomous development loop.'}

## Modified & Created Artifacts
{files_md if files_md else '- No files modified.'}

## Verification Results
- **Passed**: {state.tests.passed}
- **Failed**: {state.tests.failed}
- **Total**: {state.tests.total}
- **Exit Code**: {state.tests.exit_code}

---
*Generated by ForgeAgent for Google Antigravity.*
"""
        path.write_text(content, encoding="utf-8")
        return path

    def write_verification_report(self, state: TaskState) -> Path:
        """Create Antigravity Verification Results Artifact."""
        path = self.artifacts_dir / "verification_report.md"
        content = f"""# Verification Results Report

> **Antigravity Verifiable Artifact**  
> Task ID: `{state.task_id}`

## Test Execution Summary
| Metric | Value |
|---|---|
| Status | {'PASSED' if state.tests.failed == 0 else 'FAILED'} |
| Tests Passed | {state.tests.passed} |
| Tests Failed | {state.tests.failed} |
| Total Tests | {state.tests.total} |
| Exit Code | {state.tests.exit_code} |

## Raw Test Runner Output
```text
{state.tests.output or 'All automated tests succeeded.'}
```
"""
        path.write_text(content, encoding="utf-8")
        return path
